#!/usr/bin/env python3
"""Exhibit 3 of the rewrite: depth does not leave the basin. For every TRM/HRM model and quantizer,
exact accuracy at supervision steps 1 and 16 for fp32 and the quantized model, and the gap at each
depth; a basin miss shows as a gap that is large at both depths, a tax as a gap that is small at
both, and compounding would show as a gap that grows with depth. Data: results/breadth/<task>_all.json
(H=3 for TRM) and <task>_a8.json for static INT8 activations.

  python plots/depth_table.py            # markdown
  python plots/depth_table.py --latex    # rows for tables/tab_depth_rows.tex
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / "results" / "breadth"
spec = lambda r: r["quant"]["spec"] if isinstance(r["quant"], dict) else r["quant"]
TASKS = [("sudoku_mlp", "TRM Sudoku, MLP"), ("sudoku_attn", "TRM Sudoku, attn"), ("maze_attn", "TRM Maze"),
         ("hrm_sudoku", "HRM Sudoku"), ("hrm_maze", "HRM Maze")]
DEFAULT_H = {"sudoku_mlp": 3, "sudoku_attn": 3, "maze_attn": 3, "hrm_sudoku": 2, "hrm_maze": 2}
QUANTS = [("w8c", "INT8 per-channel"), ("w4g128", "INT4 grouped (128)"), ("w4c", "INT4 per-channel"),
          ("w4t", "INT4 per-tensor"), ("w4c+a8", "INT4 per-channel + INT8 act.")]


def cells(task):
    recs = []
    for suffix in ("_all", "_a8", "_n124", "_n816", "_deep"):
        f = B / f"{task}{suffix}.json"
        if f.exists():
            recs += json.load(open(f))["records"]
    # one H per model, the checkpoint default (TRM H=3, HRM H=2): the HRM files hold H=1-4, and a dict
    # keyed on (quantizer, steps) alone let the last file win, pairing one H's quantized row with
    # another H's fp32 (fixed Sep 24; the old HRM Maze "+ INT8 act." row compared H=3 against H=4)
    recs = [r for r in recs if r.get("H_cycles") == DEFAULT_H[task]]
    out = {}
    for r in recs:
        key = (spec(r), r["nsup"])
        assert key not in out or abs(out[key] - 100 * r["pexact"]) < 1e-9, (task, key)
        out[key] = 100 * r["pexact"]
    return out


def matrix(steps=(4, 32)):
    """Rows for tab_depth_matrix.tex: one row per quantizer, per model the gap to fp32 at each step
    count; first row fp32 accuracy. Steps 4 and 32: every model solves puzzles in fp32 at step 4
    (step 1 is near zero for TRM Sudoku-attn and HRM Sudoku), and step 32 is the deepest run for
    every weight-only cell."""
    cs = {t: cells(t) for t, _ in TASKS}
    lines = ["fp32 (accuracy) & " + " & ".join(
        " & ".join(f"{cs[t][('fp32', n)]:.1f}" for n in steps) for t, _ in TASKS) + " \\\\", "\\midrule"]
    for q, qn in QUANTS[:4]:
        cellstr = []
        for t, _ in TASKS:
            for n in steps:
                g = cs[t][(q, n)] - cs[t][("fp32", n)]
                txt = f"${g:+.1f}$".replace("+", "{+}").replace("-", "{-}")
                cellstr.append(txt)
        lines.append(f"{qn} & " + " & ".join(cellstr) + " \\\\")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    ap.add_argument("--matrix", action="store_true", help="rows for tables/tab_depth_matrix.tex")
    a = ap.parse_args()
    if a.matrix:
        print("% depth table: gap to fp32 (points) at supervision steps 4 and 32 per model; TRM H=3, HRM H=2; "
              "generated by plots/depth_table.py --matrix")
        print("\n".join(matrix()))
        return
    if a.latex:
        print("% depth-flat table: fp32 and quantized exact accuracy at steps 1 and 16, and the gap at each; generated by plots/depth_table.py --latex")
    else:
        print("| model | quantizer | fp32 n=1 | quant n=1 | gap n=1 | fp32 n=16 | quant n=16 | gap n=16 |")
        print("|---|---|---|---|---|---|---|---|")
    for task, name in TASKS:
        c = cells(task)
        if ("fp32", 1) not in c or ("fp32", 16) not in c:
            continue
        for q, qn in QUANTS:
            if (q, 1) not in c or (q, 16) not in c:
                continue
            f1, f16, q1, q16 = c[("fp32", 1)], c[("fp32", 16)], c[(q, 1)], c[(q, 16)]
            row = [f"{f1:.1f}", f"{q1:.1f}", f"{q1 - f1:+.1f}", f"{f16:.1f}", f"{q16:.1f}", f"{q16 - f16:+.1f}"]
            if a.latex:
                print(f"{name} & {qn} & " + " & ".join(row) + " \\\\")
            else:
                print(f"| {name} | {qn} | " + " | ".join(row) + " |")


if __name__ == "__main__":
    main()
