#!/usr/bin/env python3
"""Exhibit 4 of the rewrite: granularity decides the side of the boundary, the mixer decides the
width. Part A: per family (released checkpoints, step 16), exact accuracy under INT4 per-tensor,
per-channel and grouped-128 scales, with fp32. Part B: the thirteen trained Sudoku variants:
fp32, INT4 per-tensor, INT4 per-channel, and the weight-noise sigma at which the median of three
draws halves. Data: results/breadth/<task>_all.json; results/breadth/p4d/variants_noise/*.json.

  python plots/granularity_table.py [--latex]
"""
import argparse
import glob
import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / "results" / "breadth"
spec = lambda r: r["quant"]["spec"] if isinstance(r["quant"], dict) else r["quant"]
TASKS = [("sudoku_mlp", "TRM Sudoku, MLP"), ("sudoku_attn", "TRM Sudoku, attn"), ("maze_attn", "TRM Maze"),
         ("hrm_sudoku", "HRM Sudoku"), ("hrm_maze", "HRM Maze")]
DEFAULT_H = {"sudoku_mlp": 3, "sudoku_attn": 3, "maze_attn": 3, "hrm_sudoku": 2, "hrm_maze": 2}
SIG = ["0.05", "0.1", "0.15", "0.2", "0.3", "0.5", "0.7"]


def family_rows():
    rows = []
    for task, name in TASKS:
        recs = []
        for suffix in ("_all", "_n816"):
            f = B / f"{task}{suffix}.json"
            if f.exists():
                recs += json.load(open(f))["records"]
        # checkpoint-default H only (TRM 3, HRM 2); the HRM files hold H=1-4 and the dict below kept
        # whichever H came last (fixed Sep 24)
        recs = [r for r in recs if r["nsup"] == 16 and r.get("H_cycles") == DEFAULT_H[task]]
        c = {spec(r): 100 * r["pexact"] for r in recs}
        rows.append((name, c.get("fp32"), c.get("w4t"), c.get("w4c"), c.get("w4g128")))
    return rows


def variant_rows():
    rows = []
    for f in sorted(glob.glob(str(B / "p4d" / "variants_noise" / "*.json"))):
        if "seed" in f:
            continue
        v = Path(f).stem
        draws = {0: json.load(open(f))["records"]}
        for sd in (1, 2):
            fs_ = B / "p4d" / "variants_noise" / f"{v}_seed{sd}.json"
            if fs_.exists():
                draws[sd] = json.load(open(fs_))["records"]
        acc = lambda sd, q: next((100 * r["pexact"] for r in draws[sd] if spec(r) == q and r["nsup"] == 16), None)
        fp = acc(0, "fp32")
        med = {x: st.median(a for sd in draws if (a := acc(sd, f"noise{x}")) is not None) for x in SIG}
        half = next((x for x in SIG if med[x] is not None and med[x] < 0.5 * fp), None)
        mixer = "attention" if "attn" in v else "MLP"
        width = v.split("_w")[1].split("_")[0]
        seed = v.split("_s")[-1]
        rows.append((mixer, width, seed, fp, acc(0, "w4t"), acc(0, "w4c"), half or f">{SIG[-1]}"))
    return rows


def condensed_rows():
    """Part B folded to one row per mixer and width: fp32, INT4 per-tensor and the half-accuracy
    noise sigma for each seed, as 's0 / s1 / s2' (tables/tab_mixer_rows.tex)."""
    by = {}
    for mixer, width, seed, fp, t, c, half in variant_rows():
        by.setdefault((mixer, int(width)), []).append((int(seed), fp, t, half))
    out = []
    for (mixer, width) in sorted(by, key=lambda k: (k[0] != "MLP", k[1])):
        rr = sorted(by[(mixer, width)])
        j = lambda i, fmt: " / ".join(fmt(r[i]) for r in rr)
        out.append(f"{mixer} & {width} & {j(1, f)} & {j(2, f)} & {j(3, str)} \\\\")
    return out


def f(x):
    return "--" if x is None else f"{x:.1f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    ap.add_argument("--mixer", action="store_true", help="condensed Part B rows for tables/tab_mixer_rows.tex")
    a = ap.parse_args()
    if a.mixer:
        print("% trained Sudoku models, one row per mixer and width, seeds as s0 / s1 / s2: fp32, INT4 per-tensor, "
              "weight-noise sigma at which the median of three draws halves; generated by plots/granularity_table.py --mixer")
        print("\n".join(condensed_rows()))
        return
    if a.latex:
        print("% Part A: released checkpoints at step 16: fp32, INT4 per-tensor, per-channel, grouped-128; generated by plots/granularity_table.py --latex")
        for name, fp, t, c, g in family_rows():
            print(f"{name} & {f(fp)} & {f(t)} & {f(c)} & {f(g)} \\\\")
        print("% Part B: trained Sudoku variants (step 65,100): mixer, width, seed, fp32, INT4 per-tensor, INT4 per-channel, sigma at which the median of three noise draws halves")
        for mixer, width, seed, fp, t, c, half in variant_rows():
            print(f"{mixer} & {width} & {seed} & {f(fp)} & {f(t)} & {f(c)} & {half} \\\\")
    else:
        print("| model | fp32 | INT4 per-tensor | INT4 per-channel | INT4 grouped-128 |")
        print("|---|---|---|---|---|")
        for name, fp, t, c, g in family_rows():
            print(f"| {name} | {f(fp)} | {f(t)} | {f(c)} | {f(g)} |")
        print("\n| mixer | width | seed | fp32 | INT4 per-tensor | INT4 per-channel | σ½ (median of 3 draws) |")
        print("|---|---|---|---|---|---|---|")
        for mixer, width, seed, fp, t, c, half in variant_rows():
            print(f"| {mixer} | {width} | {seed} | {f(fp)} | {f(t)} | {f(c)} | {half} |")


if __name__ == "__main__":
    main()
