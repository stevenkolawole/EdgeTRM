#!/usr/bin/env python3
"""Exhibit 7 of the rewrite: AUROC for "the answer is wrong", per family and quantizer, of three
per-puzzle signals at the last supervision step (16): the model's own halting head (reference-free,
learned), the convergence residual (reference-free), and fidelity to the fp32 carry (needs the
reference). Data: results/breadth/p4d/residual_<task>.json (p4d platform throughout).

  python plots/auroc_table.py            # markdown
  python plots/auroc_table.py --latex    # rows for tables/tab_auroc_rows.tex
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / "results" / "breadth" / "p4d"
spec = lambda r: r["quant"]["spec"] if isinstance(r["quant"], dict) else r["quant"]
TASKS = [("sudoku_mlp", "TRM Sudoku, MLP"), ("sudoku_attn", "TRM Sudoku, attn"), ("maze_attn", "TRM Maze"),
         ("hrm_sudoku", "HRM Sudoku"), ("hrm_maze", "HRM Maze")]
QUANTS = ["fp32", "w8c", "w4c", "w3g32", "w4t", "noise0.1", "noise0.3", "anoise0.3"]
NAMES = {"fp32": "fp32", "w8c": "INT8 per-channel", "w4c": "INT4 per-channel", "w3g32": "INT3 grouped",
         "w4t": "INT4 per-tensor", "noise0.1": "weight noise 0.1", "noise0.3": "weight noise 0.3",
         "anoise0.3": "activation noise 0.3"}


def fmt(x):
    return "--" if x is None else f"{x:.2f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    a = ap.parse_args()
    if a.latex:
        print("% AUROC for a wrong answer at supervision step 16: halting head / residual / fidelity-to-fp32; "
              "accuracy in parentheses; generated by plots/auroc_table.py --latex")
    else:
        print("| quantizer | " + " | ".join(n for _, n in TASKS) + " |")
        print("|---|" + "---|" * len(TASKS))
    data = {}
    for task, _ in TASKS:
        recs = json.load(open(B / f"residual_{task}.json"))["records"]
        nsup = str(recs[0]["nsup"])
        data[task] = {spec(r): r["summary"][nsup] for r in recs}
    for q in QUANTS:
        cells = []
        for task, _ in TASKS:
            s = data[task].get(q)
            if s is None:
                cells.append("--")
                continue
            acc = 100 * s["acc"]
            cells.append(f"{fmt(s.get('auroc_qhalt'))} / {fmt(s.get('auroc_resid_H'))} / {fmt(s.get('auroc_fid_H'))} ({acc:.0f})")
        if a.latex:
            print(NAMES[q] + " & " + " & ".join(cells) + " \\\\")
        else:
            print(f"| {NAMES[q]} | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main()
